#!/usr/bin/env python3
"""Regenerate extension/schema.js from schema/tools.json (the single source of truth)."""
import json
import os

ROOT = os.path.dirname(os.path.abspath(__file__))
PREFIX = "// GENERATED by gen_schema.py from schema/tools.json. Do not edit.\nconst ZB_SCHEMA = "
SUFFIX = ";\nif (typeof module !== \"undefined\") module.exports = { ZB_SCHEMA };\n"


def render():
    with open(os.path.join(ROOT, "schema", "tools.json"), "rb") as f:
        return PREFIX + json.dumps(json.load(f), indent=1, sort_keys=True) + SUFFIX


if __name__ == "__main__":
    with open(os.path.join(ROOT, "extension", "schema.js"), "w", encoding="utf-8") as f:
        f.write(render())
    print("wrote extension/schema.js")
